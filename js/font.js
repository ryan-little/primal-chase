const cache = new Map();

function glyphSheet(color, shadow) {
  const key = color + '|' + shadow;
  if (cache.has(key)) return cache.get(key);
  const chars = Object.keys(GLYPHS);
  const c = canvas(chars.length * 7, 9);
  const x = c.getContext('2d');
  const map = {};
  chars.forEach((ch, i) => {
    map[ch] = i * 7;
    const rows = GLYPHS[ch].split(' ');
    for (let pass = 0; pass < 2; pass++) {
      x.fillStyle = pass === 0 ? shadow : color;
      const o = pass === 0 ? 1 : 0;
      rows.forEach((row, ry) => {
        for (let rx = 0; rx < 5; rx++) if (row[rx] === '1') x.fillRect(i * 7 + rx + o, ry + o, 1, 1);
      });
    }
  });
  const s = { img: c, map };
  cache.set(key, s);
  return s;
}

export function textWidth(str, scale = 1) {
  return str.length * 6 * scale - scale;
}

export function drawText(ctx, str, x, y, { color = '#fff', shadow = '#1a110c', scale = 1, align = 'left' } = {}) {
  const s = glyphSheet(color, shadow);
  str = String(str).toUpperCase();
  let cx = Math.round(align === 'center' ? x - textWidth(str, scale) / 2 : align === 'right' ? x - textWidth(str, scale) : x);
  const cy = Math.round(y);
  for (const ch of str) {
    const gx = s.map[ch] ?? s.map['?'];
    if (ch !== ' ') ctx.drawImage(s.img, gx, 0, 7, 9, cx, cy, 7 * scale, 9 * scale);
    cx += 6 * scale;
  }
}
